"""Контент внутренних страниц. Разметку собирает pagekit.py.

Тексты и цифры перенесены из прототипа клиента; для страницы ВПИ приоритет
у обновлённой концепции из п. 9.3 ТЗ. Ничего не выдумано — где данных нет,
блока нет.

Запуск:  python tools/build-pages.py
"""

import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pagekit as k  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'site', '4')

DIRECTION_SCRIPTS = ('model-pick.js', 'form.js', 'app.js')
PLAIN_SCRIPTS = ('form.js', 'app.js')


def build(key, depth, out, title, description, extra_css, scripts, topline, skip,
          blocks=(), cta_home=False):
    ctx = k.Ctx(key, depth)
    cta = ctx.url('home') + '#contact' if cta_home else '#contact'
    parts = [k.head(ctx, title, description, extra_css),
             k.chrome_top(ctx, topline, skip, cta)]
    for block in blocks:
        parts.append(block(ctx) if callable(block) else block)
    parts.append(k.chrome_bottom(ctx, scripts))
    path = os.path.join(ROOT, out)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    io.open(path, 'w', encoding='utf-8', newline='\n').write(''.join(parts))
    return path


